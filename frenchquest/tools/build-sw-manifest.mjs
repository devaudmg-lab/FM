// Generates sw-manifest.js: the list of app-shell files to precache, versioned by content hash.
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'assets/fonts', 'assets/icons', 'data/course.json'];
const files = [];
const walk = p => {
  const abs = join(root, p);
  if (statSync(abs).isDirectory()) for (const f of readdirSync(abs)) walk(join(p, f));
  else files.push(p.replace(/\\/g, '/'));
};
include.forEach(walk);
const hash = createHash('sha1');
for (const f of files.sort()) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 10);
const shell = ['./', ...files];
writeFileSync(join(root, 'sw-manifest.js'), `// Generated by tools/build-sw-manifest.mjs — do not edit.\nself.FQ_VERSION = '${version}';\nself.FQ_SHELL = ${JSON.stringify(shell, null, 1)};\n`);
console.log(`sw-manifest.js: ${shell.length} files, version ${version}`);
